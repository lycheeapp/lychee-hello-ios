#!/usr/bin/env bash
# Writes Config/Secrets.xcconfig (gitignored) with the production LYCHEE-SIGN-V1 key, which
# Release.xcconfig includes last. Run it on the build Mac before archiving for the App Store.
#
#   scripts/make-secrets-xcconfig.sh ~/secure/hello-ios-prod.pem hello-ios-prod-key-1
#
# The key must be RSA-2048 in PKCS#1 form ("BEGIN RSA PRIVATE KEY"), which is what RequestSigner
# reads. Make one with:
#   openssl genrsa -traditional -out hello-ios-prod.pem 2048   # Homebrew OpenSSL 3
#   openssl genrsa -out hello-ios-prod.pem 2048                # macOS's built-in LibreSSL
# and register its public half (openssl rsa -in hello-ios-prod.pem -pubout) on the backend under
# client hello-ios with the same key id.
#
# xcconfig values can't hold newlines and treat // as the start of a comment, so the PEM is written
# with its newlines as the two characters \n (RequestSigner turns them back) and every / as /$()
# (Xcode expands $() to nothing, so no // survives into the file).
set -euo pipefail

if [ $# -ne 2 ]; then
  echo "usage: $0 <path/to/hello-ios-prod.pem> <key-id>" >&2
  exit 64
fi
pem="$1"
key_id="$2"

if [ ! -f "$pem" ]; then
  echo "error: no such file: $pem" >&2
  exit 66
fi
if [ "$(head -1 "$pem")" != "-----BEGIN RSA PRIVATE KEY-----" ]; then
  echo "error: $pem is not a PKCS#1 RSA key (first line must be -----BEGIN RSA PRIVATE KEY-----)." >&2
  echo "       Convert it with: openssl rsa -traditional -in $pem -out hello-ios-prod-pkcs1.pem" >&2
  echo "       (with macOS's built-in LibreSSL, drop -traditional)" >&2
  exit 65
fi
if ! [[ "$key_id" =~ ^[A-Za-z0-9._-]+$ ]]; then
  echo "error: the key id may only contain letters, digits, '.', '_' and '-'" >&2
  exit 65
fi

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/Config/Secrets.xcconfig"

value="$(awk '{ printf "%s\\n", $0 }' "$pem" | sed 's#/#/$()#g')"

umask 077
{
  echo "// GENERATED by scripts/make-secrets-xcconfig.sh — production signing key. NEVER COMMIT."
  echo "LYCHEE_SIGNING_KEY_ID = $key_id"
  echo "LYCHEE_SIGNING_PRIVATE_KEY = $value"
} > "$out"

if git -C "$root" check-ignore -q "$out"; then
  echo "Wrote $out (gitignored) with key id $key_id."
else
  echo "warning: $out is NOT gitignored. Do not commit it." >&2
fi
